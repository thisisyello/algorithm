'''
문제 설명
사대 M개가 x축 위에 있고, 동물 N마리가 평면 위에 있습니다.
사대의 위치를 x_i, 동물의 위치를 (a, b)라고 할 때, 그 사대에서 동물까지의 거리는:
|x_i - a| + b
로 계산합니다.
이 값이 사정거리 L 이하라면 해당 동물을 잡을 수 있습니다.
잡을 수 있는 동물의 수를 구하세요. 레드의 노트

입력
첫째 줄에:
M N L
이 주어집니다.
둘째 줄에는 사대 M개의 x좌표가 주어집니다.
그다음 N개의 줄에는 각 동물의 좌표 (x, y)가 주어집니다.
입력 예시
4 8 4
6 1 4 9
7 2
3 3
4 5
5 1
2 2
1 4
8 4
9 4

제한
1 ≤ M ≤ 100,000
1 ≤ N ≤ 100,000
1 ≤ L ≤ 1,000,000,000
모든 좌표값 ≤ 1,000,000,000


출력
잡을 수 있는 동물의 수를 출력합니다.
출력 예시
6
'''